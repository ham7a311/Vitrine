const cache = new Map<string, ComponentType<DemoProps>>();

export function getDemo(slug: string): ComponentType<DemoProps> | null {
  const load = loaders[slug];
  if (!load) return null;
  let Demo = cache.get(slug);
  if (!Demo) {
    Demo = dynamic(load, { ssr: false, loading: () => null });
    cache.set(slug, Demo);
  }
  return Demo;
}
